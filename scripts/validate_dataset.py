#!/usr/bin/env python
"""Validate the generated dataset against its schema, ledger and behaviour rules.

Usage:
    python scripts/validate_dataset.py
    python scripts/validate_dataset.py --data-dir data/generated --schema-dir data/schema
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from ml.dataset.config import OUTPUT_DIR
from ml.dataset.validation import validate


def load_tables(data_dir: str | Path) -> dict[str, pd.DataFrame]:
    tables: dict[str, pd.DataFrame] = {}
    for path in sorted(Path(data_dir).glob("*.csv")):
        frames = pd.read_csv(path)
        for column in ("timestamp",):
            if column in frames.columns:
                frames[column] = pd.to_datetime(frames[column])
        for column in ("created_date", "target_date", "next_due_date"):
            if column in frames.columns:
                frames[column] = pd.to_datetime(frames[column])
        tables[path.stem] = frames
    return tables


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data-dir", default=OUTPUT_DIR)
    parser.add_argument("--schema-dir", default="data/schema")
    parser.add_argument("--report", default="docs/dataset_validation_report.md")
    args = parser.parse_args()

    tables = load_tables(args.data_dir)
    if not tables:
        print(f"No CSV files found in {args.data_dir}")
        return 1

    report = validate(tables, args.schema_dir)
    print(report.render())

    report_path = Path(args.report)
    if report_path.parent.exists():
        body = "\n".join(
            [
                "# Dataset Validation Report",
                "",
                "Generated by `scripts/validate_dataset.py`.",
                "",
                "```",
                report.render().strip(),
                "```",
                "",
            ]
        )
        report_path.write_text(body, encoding="utf-8")
        print(f"\nReport written to {report_path}")

    return 0 if report.passed else 1


if __name__ == "__main__":
    raise SystemExit(main())